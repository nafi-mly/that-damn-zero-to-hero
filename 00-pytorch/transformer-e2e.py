# 2. Core layers
class RMSNorm(nn.Module):
    """Root-mean-square layer norm (no mean subtraction, no bias)."""

    def __init__(self, dim: int, eps: float = 1e-6):
        super().__init__()
        self.eps = eps
        self.weight = nn.Parameter(torch.ones(dim))

    def _norm(self, x: torch.Tensor) -> torch.Tensor:
        # Computed in fp32 for stability, even under autocast.
        variance = x.pow(2).mean(-1, keepdim=True)
        return x * torch.rsqrt(variance + self.eps)

    def forward(self, x: torch.Tensor) -> torch.Tensor:
        output_dtype = x.dtype
        x = x.to(torch.float32)
        x_norm = self._norm(x)
        return (x_norm * self.weight).to(output_dtype)


def precompute_freqs_cis(dim: int, end: int, theta: float = 10000.0) -> torch.Tensor:
    """Precompute cos + i*sin for rotary position embeddings."""
    freqs = 1.0 / (theta ** (torch.arange(0, dim, 2)[: (dim // 2)].float() / dim))
    t = torch.arange(end, device=freqs.device, dtype=torch.float32)
    freqs = torch.outer(t, freqs).float()
    return torch.polar(torch.ones_like(freqs), freqs)   # complex64


def reshape_for_broadcast(freqs_cis: torch.Tensor, x: torch.Tensor) -> torch.Tensor:
    ndim = x.ndim
    assert 0 <= 1 < ndim
    assert freqs_cis.shape == (x.shape[1], x.shape[-1]), (
        f"freqs_cis {tuple(freqs_cis.shape)} vs x {tuple(x.shape)}"
    )
    shape = [d if i == 1 or i == ndim - 1 else 1 for i, d in enumerate(x.shape)]
    return freqs_cis.view(*shape)


def apply_rotary_emb(
    xq: torch.Tensor,
    xk: torch.Tensor,
    freqs_cis: torch.Tensor,
) -> Tuple[torch.Tensor, torch.Tensor]:
    """Rotate query/key vectors in the complex plane. Shapes: (B, S, H, D)."""
    xq_ = torch.view_as_complex(xq.float().reshape(*xq.shape[:-1], -1, 2))
    xk_ = torch.view_as_complex(xk.float().reshape(*xk.shape[:-1], -1, 2))
    freqs_cis = reshape_for_broadcast(freqs_cis, xq_)
    xq_out = torch.view_as_real(xq_ * freqs_cis).flatten(3)
    xk_out = torch.view_as_real(xk_ * freqs_cis).flatten(3)
    return xq_out.type_as(xq), xk_out.type_as(xk)


class KVCache:
    """Per-layer key/value cache for incremental decoding."""

    __slots__ = ("k", "v")

    def __init__(self):
        self.k: Optional[torch.Tensor] = None
        self.v: Optional[torch.Tensor] = None

    def update(self, k: torch.Tensor, v: torch.Tensor) -> Tuple[torch.Tensor, torch.Tensor]:
        if self.k is None:
            self.k, self.v = k, v
        else:
            self.k = torch.cat([self.k, k], dim=2)
            self.v = torch.cat([self.v, v], dim=2)
        return self.k, self.v

    def reset(self):
        self.k = None
        self.v = None

    @property
    def size(self) -> int:
        return 0 if self.k is None else self.k.size(2)


class Attention(nn.Module):
    """Multi-head / grouped-query causal self-attention with RoPE."""

    def __init__(self, args: ModelArgs):
        super().__init__()
        self.n_kv_heads = args.n_heads if args.n_kv_heads is None else args.n_kv_heads
        assert args.n_heads % self.n_kv_heads == 0, "n_heads must be divisible by n_kv_heads"
        self.n_local_heads = args.n_heads
        self.n_local_kv_heads = self.n_kv_heads
        self.n_rep = self.n_local_heads // self.n_local_kv_heads
        self.head_dim = args.dim // args.n_heads
        assert self.head_dim % 2 == 0, "head_dim must be even for RoPE"
        self.dropout = args.dropout

        self.wq = nn.Linear(args.dim, args.n_heads * self.head_dim, bias=False)
        self.wk = nn.Linear(args.dim, self.n_kv_heads * self.head_dim, bias=False)
        self.wv = nn.Linear(args.dim, self.n_kv_heads * self.head_dim, bias=False)
        self.wo = nn.Linear(args.n_heads * self.head_dim, args.dim, bias=False)

    def forward(
        self,
        x: torch.Tensor,
        freqs_cis: torch.Tensor,
        mask: Optional[torch.Tensor] = None,
        cache: Optional[KVCache] = None,
    ) -> torch.Tensor:
        bsz, seqlen, _ = x.shape

        xq = self.wq(x).view(bsz, seqlen, self.n_local_heads, self.head_dim)
        xk = self.wk(x).view(bsz, seqlen, self.n_local_kv_heads, self.head_dim)
        xv = self.wv(x).view(bsz, seqlen, self.n_local_kv_heads, self.head_dim)

        # RoPE is applied only to the *new* tokens (freqs_cis matches seqlen).
        xq, xk = apply_rotary_emb(xq, xk, freqs_cis=freqs_cis)

        # (B, S, H, D) -> (B, H, S, D)
        xq = xq.transpose(1, 2)
        xk = xk.transpose(1, 2)
        xv = xv.transpose(1, 2)

        # Append to cache (cache holds un-expanded KV heads to save memory).
        if cache is not None:
            xk, xv = cache.update(xk, xv)

        # Expand KV heads to match query heads for GQA.
        if self.n_rep > 1:
            xk = xk.repeat_interleave(self.n_rep, dim=1)
            xv = xv.repeat_interleave(self.n_rep, dim=1)

        dropout_p = self.dropout if self.training else 0.0

        if mask is not None:
            out = F.scaled_dot_product_attention(xq, xk, xv, attn_mask=mask, dropout_p=dropout_p)
        else:
            # Causal masking is only needed for a full (prefill) pass; a single
            # query token attending to the whole cache is causal by construction.
            is_causal = xq.size(2) > 1 and xq.size(2) == xk.size(2)
            out = F.scaled_dot_product_attention(
                xq, xk, xv, is_causal=is_causal, dropout_p=dropout_p
            )

        out = out.transpose(1, 2).contiguous().view(bsz, seqlen, -1)
        return self.wo(out)


class FeedForward(nn.Module):
    """SwiGLU feed-forward network."""

    def __init__(self, dim: int, hidden_dim: int, multiple_of: int,
                 ffn_dim_multiplier: Optional[float], dropout: float = 0.0):
        super().__init__()
        hidden_dim = int(2 * hidden_dim / 3)
        if ffn_dim_multiplier is not None:
            hidden_dim = int(ffn_dim_multiplier * hidden_dim)
        hidden_dim = multiple_of * ((hidden_dim + multiple_of - 1) // multiple_of)

        self.w1 = nn.Linear(dim, hidden_dim, bias=False)   # gate
        self.w2 = nn.Linear(hidden_dim, dim, bias=False)   # down
        self.w3 = nn.Linear(dim, hidden_dim, bias=False)   # up
        self.drop = nn.Dropout(dropout)

    def forward(self, x: torch.Tensor) -> torch.Tensor:
        return self.drop(self.w2(F.silu(self.w1(x)) * self.w3(x)))


class TransformerBlock(nn.Module):
    def __init__(self, layer_id: int, args: ModelArgs):
        super().__init__()
        self.layer_id = layer_id
        self.n_heads = args.n_heads
        self.dim = args.dim
        self.head_dim = args.dim // args.n_heads

        self.attention = Attention(args)
        self.feed_forward = FeedForward(
            dim=args.dim,
            hidden_dim=4 * args.dim,
            multiple_of=args.multiple_of,
            ffn_dim_multiplier=args.ffn_dim_multiplier,
            dropout=args.dropout,
        )
        self.attention_norm = RMSNorm(args.dim, eps=args.norm_eps)
        self.ffn_norm = RMSNorm(args.dim, eps=args.norm_eps)
        self.resid_drop = nn.Dropout(args.dropout)

    def forward(
        self,
        x: torch.Tensor,
        freqs_cis: torch.Tensor,
        mask: Optional[torch.Tensor] = None,
        cache: Optional[KVCache] = None,
    ) -> torch.Tensor:
        h = x + self.resid_drop(self.attention(self.attention_norm(x), freqs_cis, mask, cache))
        out = h + self.resid_drop(self.feed_forward(self.ffn_norm(h)))
        return out


class Transformer(nn.Module):
    def __init__(self, params: ModelArgs):
        super().__init__()
        self.params = params
        self.vocab_size = params.vocab_size
        self.n_layers = params.n_layers

        self.tok_embeddings = nn.Embedding(params.vocab_size, params.dim)
        self.drop = nn.Dropout(params.dropout)

        self.layers = nn.ModuleList(
            [TransformerBlock(layer_id, params) for layer_id in range(params.n_layers)]
        )

        self.norm = RMSNorm(params.dim, eps=params.norm_eps)
        self.output = nn.Linear(params.dim, params.vocab_size, bias=False)

        # RoPE table: 2x max_seq_len so generation can run past the training window.
        self.register_buffer(
            "freqs_cis",
            precompute_freqs_cis(
                params.dim // params.n_heads, params.max_seq_len * 2
            ),
            persistent=False,
        )

        self.apply(self._init_weights)
        self._scale_residual_projections()

        if params.tie_embeddings:
            self.output.weight = self.tok_embeddings.weight

    # -- initialization ----------------------------------------------------
    def _init_weights(self, module: nn.Module):
        if isinstance(module, nn.Linear):
            torch.nn.init.normal_(module.weight, mean=0.0, std=0.02)
            if module.bias is not None:
                torch.nn.init.zeros_(module.bias)
        elif isinstance(module, nn.Embedding):
            torch.nn.init.normal_(module.weight, mean=0.0, std=0.02)

    def _scale_residual_projections(self):
        """GPT-2 style scaling of the output projections of residual branches."""
        std = 0.02 / math.sqrt(2 * self.n_layers)
        for name, p in self.named_parameters():
            if name.endswith("wo.weight") or name.endswith("w2.weight"):
                torch.nn.init.normal_(p, mean=0.0, std=std)

    # -- forward -----------------------------------------------------------
    def forward(
        self,
        tokens: torch.Tensor,
        start_pos: int = 0,
        caches: Optional[List[KVCache]] = None,
        targets: Optional[torch.Tensor] = None,
        ignore_index: int = -100,
    ):
        """
        tokens   : (B, S) int64
        start_pos: absolute position of tokens[:, 0] (used with KV cache)
        caches   : list of KVCache, one per layer, or None
        targets  : (B, S) int64 -> returns (full_logits, loss)
                   None        -> returns (logits_for_last_position, None)
        """
        _bsz, seqlen = tokens.shape

        h = self.drop(self.tok_embeddings(tokens))

        if start_pos + seqlen > self.freqs_cis.shape[0]:
            raise ValueError(
                f"position {start_pos + seqlen} exceeds RoPE table "
                f"({self.freqs_cis.shape[0]}). Increase max_seq_len."
            )
        freqs_cis = self.freqs_cis[start_pos: start_pos + seqlen]

        for i, layer in enumerate(self.layers):
            cache = None if caches is None else caches[i]
            h = layer(h, freqs_cis, mask=None, cache=cache)

        h = self.norm(h)

        if targets is not None:
            logits = self.output(h)
            loss = F.cross_entropy(
                logits.view(-1, logits.size(-1)),
                targets.reshape(-1),
                ignore_index=ignore_index,
            )
            return logits, loss

        # Inference: only the last position is needed to predict the next token.
        logits = self.output(h[:, -1:, :])
        return logits, None

    @property
    def num_params(self) -> int:
        return sum(p.numel() for p in self.parameters())

    @property
    def num_params_non_embedding(self) -> int:
        n = self.num_params - self.tok_embeddings.weight.numel()
        if not self.params.tie_embeddings:
            n -= self.output.weight.numel()
        return n


# 3. Tokenizer
class CharTokenizer:
    """Minimal character-level tokenizer (no external dependencies)."""

    def __init__(self, text: Optional[str] = None, chars: Optional[str] = None):
        if chars is not None:
            self.chars = list(chars)
        elif text is not None:
            self.chars = sorted(set(text))
        else:
            raise ValueError("Provide either `text` or `chars`.")
        self.stoi = {c: i for i, c in enumerate(self.chars)}
        self.itos = {i: c for i, c in enumerate(self.chars)}

    @property
    def vocab_size(self) -> int:
        return len(self.chars)

    def encode(self, s: str) -> List[int]:
        return [self.stoi[c] for c in s if c in self.stoi]

    def decode(self, ids) -> str:
        if torch.is_tensor(ids):
            ids = ids.tolist()
        return "".join(self.itos[int(i)] for i in ids)

    def state_dict(self) -> Dict[str, Any]:
        return {"chars": "".join(self.chars)}

    @classmethod
    def from_state_dict(cls, sd: Dict[str, Any]) -> "CharTokenizer":
        return cls(chars=sd["chars"])

