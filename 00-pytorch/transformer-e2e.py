def split_train_val(data: torch.Tensor, val_frac: float = 0.1) -> Tuple[torch.Tensor, torch.Tensor]:
    n = int(len(data) * (1.0 - val_frac))
    n = max(n, 1)
    return data[:n], data[n:]


def get_batch(
    data: torch.Tensor, block_size: int, batch_size: int, device: torch.device
) -> Tuple[torch.Tensor, torch.Tensor]:
    if len(data) <= block_size + 1:
        raise ValueError(
            f"Corpus too small ({len(data)} tokens) for block_size={block_size}."
        )
    ix = torch.randint(0, len(data) - block_size - 1, (batch_size,))
    x = torch.stack([data[i: i + block_size] for i in ix])
    y = torch.stack([data[i + 1: i + 1 + block_size] for i in ix])
    return x.to(device, non_blocking=True), y.to(device, non_blocking=True)

# 5. Training utilities
def resolve_device(requested: str) -> torch.device:
    if requested == "auto":
        if torch.cuda.is_available():
            return torch.device("cuda")
        if getattr(torch.backends, "mps", None) and torch.backends.mps.is_available():
            return torch.device("mps")
        return torch.device("cpu")
    return torch.device(requested)


def resolve_dtype(requested: str, device: torch.device) -> torch.dtype:
    if requested == "auto":
        if device.type == "cuda":
            return torch.bfloat16 if torch.cuda.is_bf16_supported() else torch.float16
        return torch.float32
    return {
        "bfloat16": torch.bfloat16,
        "bf16": torch.bfloat16,
        "float16": torch.float16,
        "fp16": torch.float16,
        "float32": torch.float32,
        "fp32": torch.float32,
    }[requested]


def get_lr(step: int, cfg: TrainConfig) -> float:
    """Linear warmup followed by cosine decay."""
    if step < cfg.warmup_steps:
        return cfg.lr * (step + 1) / max(1, cfg.warmup_steps)
    if step >= cfg.max_steps:
        return cfg.min_lr
    ratio = (step - cfg.warmup_steps) / max(1, cfg.max_steps - cfg.warmup_steps)
    coeff = 0.5 * (1.0 + math.cos(math.pi * ratio))
    return cfg.min_lr + coeff * (cfg.lr - cfg.min_lr)


def build_optimizer(model: nn.Module, cfg: TrainConfig) -> torch.optim.Optimizer:
    """AdamW with weight decay only on matrices (not norms / biases / embeddings-norm)."""
    decay, no_decay = [], []
    for name, p in model.named_parameters():
        if not p.requires_grad:
            continue
        if p.dim() >= 2:
            decay.append(p)
        else:
            no_decay.append(p)
    groups = [
        {"params": decay, "weight_decay": cfg.weight_decay},
        {"params": no_decay, "weight_decay": 0.0},
    ]
    kwargs: Dict[str, Any] = dict(lr=cfg.lr, betas=(cfg.beta1, cfg.beta2))
    if torch.cuda.is_available():
        try:
            return torch.optim.AdamW(groups, fused=True, **kwargs)
        except (TypeError, RuntimeError):
            pass
    return torch.optim.AdamW(groups, **kwargs)


def make_grad_scaler(enabled: bool, device_type: str):
    try:
        return torch.amp.GradScaler(device_type, enabled=enabled)
    except (AttributeError, TypeError):
        return torch.cuda.amp.GradScaler(enabled=enabled)


def unwrap(model: nn.Module) -> nn.Module:
    return getattr(model, "_orig_mod", model)


@torch.no_grad()
def estimate_loss(
    model: nn.Module,
    data: torch.Tensor,
    block_size: int,
    batch_size: int,
    device: torch.device,
    ctx,
    eval_iters: int,
) -> float:
    model.eval()
    losses = torch.zeros(eval_iters)
    for i in range(eval_iters):
        x, y = get_batch(data, block_size, batch_size, device)
        with ctx:
            _, loss = model(x, targets=y)
        losses[i] = loss.detach().float().cpu()
    model.train()
    return losses.mean().item()


def save_checkpoint(
    path: str,
    model: nn.Module,
    optimizer: Optional[torch.optim.Optimizer],
    step: int,
    model_args: ModelArgs,
    train_cfg: TrainConfig,
    tokenizer: CharTokenizer,
    best_val: float,
):
    os.makedirs(os.path.dirname(path) or ".", exist_ok=True)
    torch.save(
        {
            "model": unwrap(model).state_dict(),
            "optimizer": optimizer.state_dict() if optimizer is not None else None,
            "step": step,
            "best_val": best_val,
            "model_args": asdict(model_args),
            "train_config": asdict(train_cfg),
            "tokenizer": tokenizer.state_dict(),
            "format_version": 1,
        },
        path,
    )


def load_checkpoint(path: str, device: torch.device):
    ckpt = torch.load(path, map_location=device, weights_only=False)
    mcfg = ModelArgs(**ckpt["model_args"])
    model = Transformer(mcfg)
    model.load_state_dict(ckpt["model"])
    model.to(device)
    model.eval()
    tokenizer = CharTokenizer.from_state_dict(ckpt["tokenizer"])
    return model, tokenizer, mcfg, ckpt


# 6. The training loop
def train(
    model: Transformer,
    tokenizer: CharTokenizer,
    train_data: torch.Tensor,
    val_data: torch.Tensor,
    mcfg: ModelArgs,
    tcfg: TrainConfig,
) -> Transformer:
    device = resolve_device(tcfg.device)
    device_type = device.type
    ptdtype = resolve_dtype(tcfg.dtype, device)

    model.to(device)
    model.train()

    use_amp = device_type == "cuda" and ptdtype in (torch.bfloat16, torch.float16)
    ctx = (
        torch.autocast(device_type=device_type, dtype=ptdtype)
        if use_amp
        else contextlib.nullcontext()
    )
    use_scaler = use_amp and ptdtype == torch.float16
    scaler = make_grad_scaler(use_scaler, device_type)

    optimizer = build_optimizer(model, tcfg)

    block_size = min(mcfg.max_seq_len, len(train_data) - 2)
    best_val = float("inf")
    ckpt_path = os.path.join(tcfg.out_dir, "ckpt.pt")
    best_path = os.path.join(tcfg.out_dir, "ckpt_best.pt")

